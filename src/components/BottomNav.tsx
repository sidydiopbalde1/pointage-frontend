export default function BottomNav() {
  const pathname = usePathname();
  const { user, isAdmin, isManager } = useAuth();
  const isDesktop = useIsDesktop();

  if (!user || isDesktop) return null;

  const items = isAdmin
    ? [
        { href: '/dashboard', label: 'Accueil', icon: <HomeIcon /> },
        { href: '/attendance', label: 'Présences', icon: <ClockIcon /> },
        { href: '/qr-code', label: 'Scanner', icon: <QrIcon /> },
        { href: '/users', label: 'Équipe', icon: <UsersIcon /> },
        { href: '/settings', label: 'Paramètres', icon: <SettingsIcon /> },
      ]
    : isManager
    ? [
        { href: '/dashboard', label: 'Accueil', icon: <HomeIcon /> },
        { href: '/attendance', label: 'Présences', icon: <ClockIcon /> },
        { href: '/leaves', label: 'Congés', icon: <CalIcon /> },
        { href: '/absences', label: 'Absences', icon: <AbsIcon /> },
        { href: '/settings', label: 'Paramètres', icon: <SettingsIcon /> },
      ]
    : [
        { href: '/attendance', label: 'Présences', icon: <ClockIcon /> },
        { href: '/leaves', label: 'Congés', icon: <CalIcon /> },
        { href: '/qr-code', label: 'QR Code', icon: <QrIcon /> },
        { href: '/settings', label: 'Paramètres', icon: <SettingsIcon /> },
      ];

  return (
    <nav className="bottom-nav">
      {items.map((item) => {
        const active = pathname === item.href || pathname.startsWith(item.href + '/');
        return (
          <Link key={item.href} href={item.href} className={`bottom-nav-item ${active ? 'active' : ''}`}>
            <motion.div
              className="nav-icon-wrap"
              whileTap={{ scale: 0.88 }}
              animate={active ? { scale: 1.08 } : { scale: 1 }}
              transition={{ duration: 0.18, ease: [0.34, 1.56, 0.64, 1] }}
            >
              {item.icon}
            </motion.div>
            <motion.span
              animate={active ? { opacity: 1, y: 0 } : { opacity: 0.65, y: 1 }}
              transition={{ duration: 0.2 }}
            >
              {item.label}
            </motion.span>
          </Link>
        );
      })}
    </nav>
  );
}
